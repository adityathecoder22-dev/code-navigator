"""On-disk layout of an index. By default it lives inside the indexed repository:

<repo>/.code-navigator/
    manifest.json      project info, stats, embedder/vector settings used
    services.json      detected services
    dependencies.json  dependency graph edges (with file:line evidence)
    callgraph.json     function-level call graph + HTTP entry points
    graph.html         interactive viewer (open in a browser)
    chunks.jsonl       every chunk (text + metadata) - used for lookups and vectorless retrieval
    tree.json          vectorless hierarchical index with summaries
    summary_cache.json LLM summaries keyed by prompt hash (re-used on re-index)
    vectors/           vector store (simple/ or chroma/)
"""
from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path

from .config import INDEX_DIR_NAME

GITIGNORE = "# Generated by code-navigator. Delete this file if you want to commit the index.\n*\n"


@dataclass
class IndexPaths:
    root: Path

    @classmethod
    def for_repo(cls, repo: str | Path, index_dir: str | Path | None = None) -> "IndexPaths":
        if index_dir:
            return cls(Path(index_dir).expanduser().resolve())
        return cls(Path(repo).expanduser().resolve() / INDEX_DIR_NAME)

    @property
    def manifest(self) -> Path:
        return self.root / "manifest.json"

    @property
    def services(self) -> Path:
        return self.root / "services.json"

    @property
    def dependencies(self) -> Path:
        return self.root / "dependencies.json"

    @property
    def chunks(self) -> Path:
        return self.root / "chunks.jsonl"

    @property
    def tree(self) -> Path:
        return self.root / "tree.json"

    @property
    def callgraph(self) -> Path:
        return self.root / "callgraph.json"

    @property
    def graph_html(self) -> Path:
        return self.root / "graph.html"

    @property
    def summary_cache(self) -> Path:
        return self.root / "summary_cache.json"

    @property
    def vectors(self) -> Path:
        return self.root / "vectors"

    @property
    def gitignore(self) -> Path:
        return self.root / ".gitignore"

    def exists(self) -> bool:
        return self.manifest.exists()
